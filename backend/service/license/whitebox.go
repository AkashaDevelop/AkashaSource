const xorMask byte = 0x5A

//go:noinline
func unmask(masked []byte) []byte {
	result := make([]byte, len(masked))
	for i, b := range masked {
		result[i] = b ^ xorMask
	}
	return result
}

//go:noinline
func zeroBytes(b []byte) {
	if len(b) == 0 {
		return
	}
	for i := range b {
		b[i] = 0
	}
	runtime.KeepAlive(b)
}

// verifyShardIntegrity 校验分片未被篡改
//
//go:noinline
func verifyShardIntegrity() bool {
	h := sha256.New()
	h.Write(shardA)
	h.Write(shardB)
	h.Write(shardC)
	sum := h.Sum(nil)
	for i := 0; i < 16; i++ {
		if sum[i] != shardChecksum[i] {
			return false
		}
	}
	return true
}

// reassembleKey 运行时重组 AES-256 密钥
// K = S1 ^ S2 ^ S3 ^ S4
// S1 = shardA ^ SHA256(unmask(seedMask1))
// S2 = shardB ^ SHA256(unmask(seedMask2))
// S3 = shardC ^ SHA256(unmask(seedMask3))
// S4 = SHA256(unmask(seedMask4))  ← 运行时派生
//
//go:noinline
func reassembleKey() []byte {
	m1 := sha256.Sum256(unmask(seedMask1))
	m2 := sha256.Sum256(unmask(seedMask2))
	m3 := sha256.Sum256(unmask(seedMask3))
	s4 := sha256.Sum256(unmask(seedMask4))

	key := make([]byte, 32)
	for i := 0; i < 32; i++ {
		key[i] = shardA[i] ^ m1[i] ^ shardB[i] ^ m2[i] ^ shardC[i] ^ m3[i] ^ s4[i]
	}
	return key
}

var decryptedSecrets struct {
	targetOrg                 string
	gistId                    string
	gistToken                 string
	hmacSecret                []byte
	licenseGithubClientId     string
	licenseGithubClientSecret string
	initialized               bool
	decryptFailed             bool // 解密失败(tampered) → fail-closed
}

//go:noinline
func initSecrets() {
	if decryptedSecrets.initialized {
		return
	}
	decryptedSecrets.initialized = true

	// 完整性校验: 分片被篡改 → fail-closed
	if !verifyShardIntegrity() {
		decryptedSecrets.decryptFailed = true
		return
	}

	key := reassembleKey()
	defer zeroBytes(key)

	block, err := aes.NewCipher(key)
	if err != nil {
		decryptedSecrets.decryptFailed = true
		return
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		decryptedSecrets.decryptFailed = true
		return
	}

	decrypt := func(ct, nonce []byte) []byte {
		pt, err := gcm.Open(nil, nonce, ct, nil)
		if err != nil {
			return nil
		}
		return pt
	}

	org := decrypt(ctTargetOrg, nonceTargetOrg)
	gid := decrypt(ctGistId, nonceGistId)
	gt := decrypt(ctGistToken, nonceGistToken)
	hs := decrypt(ctHmacSecret, nonceHmacSecret)
	ocid := decrypt(ctOauthClientId, nonceOauthClientId)
	ocs := decrypt(ctOauthClientSecret, nonceOauthClientSecret)

	// 任一解密失败 → fail-closed
	if org == nil || gid == nil || gt == nil || hs == nil || ocid == nil || ocs == nil {
		decryptedSecrets.decryptFailed = true
		return
	}

	decryptedSecrets.targetOrg = string(org)
	decryptedSecrets.gistId = string(gid)
	decryptedSecrets.gistToken = string(gt)
	decryptedSecrets.hmacSecret = hs
	decryptedSecrets.licenseGithubClientId = string(ocid)
	decryptedSecrets.licenseGithubClientSecret = string(ocs)

	runtime.GC()
}

func ensureInit() {
	if !decryptedSecrets.initialized {
		initSecrets()
	}
}

func getSecretTargetOrg() string {
	ensureInit()
	return decryptedSecrets.targetOrg
}

func getSecretGistId() string {
	ensureInit()
	return decryptedSecrets.gistId
}

func getSecretGistToken() string {
	ensureInit()
	return decryptedSecrets.gistToken
}

func getSecretHmacSecret() []byte {
	ensureInit()
	return decryptedSecrets.hmacSecret
}

func getSecretOauthClientId() string {
	ensureInit()
	return decryptedSecrets.licenseGithubClientId
}

func getSecretOauthClientSecret() string {
	ensureInit()
	return decryptedSecrets.licenseGithubClientSecret
}
